// Generates the two SYNTHETIC sample CSVs in samples/ from the simulation module plus seeded noise.
// These are NOT real flight data. Run: node tools/make-samples.mjs
import { writeFileSync } from 'node:fs';
import { simulate } from '../src/physics.js';

function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const gauss = (r) => Math.sqrt(-2 * Math.log(r() || 1e-9)) * Math.cos(2 * Math.PI * r());

function resample(frames, hz) {
  const out = [];
  const end = frames[frames.length - 1].t;
  let j = 0;
  for (let t = 0; t <= end; t += 1 / hz) {
    while (j < frames.length - 2 && frames[j + 1].t < t) j++;
    const a = frames[j], b = frames[j + 1];
    const f = Math.min(1, Math.max(0, (t - a.t) / (b.t - a.t)));
    const L = (k) => a[k] + (b[k] - a[k]) * f;
    out.push({ t, alt: L('alt'), v: L('vAlt'), acc: L('acc'), x: L('x'), y: L('y') });
  }
  return out;
}

const banner = [
  '# SYNTHETIC EXAMPLE DATA - NOT a real StarRocket flight.',
  '# Generated by tools/make-samples.mjs from the built-in physics model plus seeded random noise.',
];

// Sample 1: barometer only, feet + milliseconds, 20 Hz, 1 s of pad samples before launch.
{
  const sim = simulate({ burnTime: 2.2, thrust: 300, mass: 2.8, mainDeployAlt: 250, windSpeed: 3, windDir: 90 });
  const r = rng(1234);
  const rows = resample(sim.frames, 20);
  const lines = [...banner, '# Columns: barometer only, time in milliseconds, altitude in feet (AGL).', 'time_ms,altitude_ft'];
  const pad = 20; // 1 s of pad samples
  for (let i = -pad; i < 0; i++) lines.push(`${Math.round((i + pad) * 50)},${(gauss(r) * 0.3).toFixed(2)}`);
  rows.forEach((p, i) => {
    lines.push(`${Math.round((i + pad) * 50)},${((p.alt + gauss(r) * 0.35) / 0.3048).toFixed(2)}`);
  });
  writeFileSync(new URL('../samples/synthetic-baro-only.csv', import.meta.url), lines.join('\n') + '\n');
}

// Sample 2: baro + accel + GPS-style lat/lon (placed at 0,0 on purpose) + event column, SI units, 10 Hz.
{
  const sim = simulate({ burnTime: 1.6, thrust: 220, mass: 2.2, drogueDeployAlt: 0, mainDeployAlt: 350, windSpeed: 6, windDir: 135 });
  const r = rng(98765);
  const rows = resample(sim.frames, 10);
  const ev = Object.fromEntries(sim.events.map((e) => [e.name, e.t]));
  const mPerDeg = 111320;
  const lines = [...banner, '# Columns: SI units. lat/lon are fake offsets from 0,0 (not a real location).',
    'time_s,alt_m,velocity_mps,accel_mps2,lat,lon,event'];
  let prevLabel = '';
  rows.forEach((p) => {
    const label = p.t >= ev.landing ? 'LANDED' : p.t >= ev.main ? 'MAIN' : p.t >= ev.drogue ? 'DROGUE' : p.t >= ev.burnout ? 'COAST' : p.t >= 0.1 ? 'BOOST' : 'PAD';
    const out = label !== prevLabel ? label : '';
    prevLabel = label;
    const lat = (p.y + gauss(r) * 0.5) / mPerDeg;
    const lon = (p.x + gauss(r) * 0.5) / mPerDeg;
    lines.push([
      p.t.toFixed(2), (p.alt + gauss(r) * 0.4).toFixed(2), (p.v + gauss(r) * 0.3).toFixed(2),
      (p.acc + gauss(r) * 1.0).toFixed(2), lat.toFixed(7), lon.toFixed(7), out,
    ].join(','));
  });
  writeFileSync(new URL('../samples/synthetic-gps-events.csv', import.meta.url), lines.join('\n') + '\n');
}
